def clear_previous_sweep(output):
    """Remove only artifacts generated by this script before a new sweep."""
    output = Path(output)
    removed = False
    for filename in GENERATED_SWEEP_FILES:
        path = output / filename
        if path.is_file() or path.is_symlink():
            path.unlink()
            removed = True
    cells = output / "cells"
    if cells.is_dir():
        shutil.rmtree(cells)
        removed = True
    if removed:
        print(f"Overwriting previous sweep results in {output.resolve()}")


def departure_epoch(value):
    """Accept the nominal reader's MJD2000 UTC days or an ISO calendar date."""
    try:
        return float(value)
    except ValueError:
        try:
            date = datetime.strptime(value, "%Y-%m-%d")
        except ValueError as exc:
            raise argparse.ArgumentTypeError("Use MJD2000 days or YYYY-MM-DD") from exc
        return (date - datetime(2000, 1, 1, 12)).total_seconds() / 86400.0


def projected_state(body, epoch, meta_kernel):
    """SPICE AU, AU/day -> polar state [rho,theta,rho_dot,theta_dot]."""
    position, velocity_day = spice_state(body, float(epoch), meta_kernel)
    position = np.asarray(position, dtype=float)
    velocity_day = np.asarray(velocity_day, dtype=float)
    x, y = position[:2]
    vx, vy = velocity_day[:2] * DAYS_PER_CANONICAL_TIME
    rho = float(np.hypot(x, y))
    if not np.isfinite(rho) or rho <= 0:
        raise ValueError(f"Invalid projected radius for {body} at MJD2000 {epoch}")
    state = np.array([rho, np.arctan2(y, x), (x * vx + y * vy) / rho,
                      (x * vy - y * vx) / rho**2])
    if not np.all(np.isfinite(state)):
        raise ValueError(f"Invalid projected state for {body} at MJD2000 {epoch}")
    record = {"body": body, "mjd2000_utc": float(epoch),
              "spice_position_au": position.tolist(), "spice_velocity_au_day": velocity_day.tolist(),
              "projected_position_au": [float(x), float(y), 0.0],
              "projected_velocity_canonical": [float(vx), float(vy), 0.0],
              "polar_state_canonical": state.tolist()}
    return state, record


def solve_cell(task):
    """Solve one independent (N, departure, TOF) cell in a worker process."""
    cell = Path(task["cell"])
    cell.mkdir(parents=True, exist_ok=True)
    ephemeris_payload = task.get("ephemeris_payload")
    if ephemeris_payload is not None:
        (cell / "ephemeris.json").write_text(
            json.dumps(ephemeris_payload, indent=2) + "\n"
        )
    row = task["row"]
    peak = sampled_peak = delta_v = float("nan")
    control_points = np.full((task["options"].n_ctrl, 2), np.nan)
    with (cell / "solver.log").open("w") as log:
        try:
            with redirect_stdout(log), redirect_stderr(log):
                result = solve(
                    task["options"],
                    endpoint_velocities=task["endpoint_velocities"],
                )
            peak = float(result["required_peak_acceleration_bound"])
            if not result["numerical_checks_passed"] or not np.isfinite(peak):
                raise RuntimeError("Solution failed numerical acceptance checks")
            sampled_peak = float(result["sampled_max_acceleration"])
            delta_v = float(result["delta_v_reference_km_s"])
            control_points = np.asarray(
                result["control_coefficients_rho_theta"], dtype=float
            )
            row.update(
                status="accepted",
                peak_bound=peak,
                sampled_peak=sampled_peak,
                delta_v_reference_km_s=delta_v,
                delta_v_reference_error_km_s=result["delta_v_reference_error_km_s"],
                delta_v_reference_converged=result["reference_converged"],
                gap_to_u_max=result["peak_bound_gap"],
                available_limit_checks_passed=result["available_limit_numerical_checks_passed"],
            )
        except Exception as exc:
            row["error"] = f"{type(exc).__name__}: {exc}"
            log.write("\n" + traceback.format_exc() + "\n")
    return task["indices"], row, peak, sampled_peak, delta_v, control_points


def aggregate_saved_control_points(output, config, departure, tof, revolutions, peak):
    """Build the nominal-style control-point archive from per-cell JSON files."""
    n_ctrl = int(config["n_ctrl"])
    degree = int(config["degree"])
    controls = np.full(
        (len(revolutions), len(tof), len(departure), n_ctrl, 2), np.nan
    )
    recovered = 0
    for ni, n_rev in enumerate(revolutions):
        for ti in range(len(tof)):
            for di in range(len(departure)):
                if not np.isfinite(peak[ni, ti, di]):
                    continue
                path = output / "cells" / f"N{n_rev}_tof{ti:03d}_dep{di:03d}" / "solution.json"
                if not path.is_file():
                    continue
                data = json.loads(path.read_text())
                value = np.asarray(data.get("control_coefficients_rho_theta", []), dtype=float)
                if value.shape == (n_ctrl, 2) and np.all(np.isfinite(value)):
                    controls[ni, ti, di] = value
                    recovered += 1
    np.savez_compressed(
        output / "control_points.npz",
        control_points=controls,
        departure_mjd2000=departure,
        tof_days=tof,
        N=revolutions,
        accepted=np.isfinite(peak),
        degree=np.asarray(degree),
        n_ctrl=np.asarray(n_ctrl),
        knots=make_clamped_knots(n_ctrl, degree),
        coordinates=np.asarray(["rho", "theta"]),
        array_layout=np.asarray(
            "control_points[N_index,tof_index,departure_index,control_index,coordinate]"
        ),
    )
    print(f"Control-point archive: recovered {recovered} accepted solutions.")


def plot_maps(output, show=False):
    """Redraw saved maps without rerunning any optimization."""
    import matplotlib

    if not show:
        matplotlib.use("Agg")
    import matplotlib.pyplot as plt
    from matplotlib.colors import BoundaryNorm, ListedColormap, LogNorm, Normalize

    config = json.loads((output / "config.json").read_text())
    # Old saved sweeps used nondimensional grid coordinates.
    time_unit = config.get("grid_time_unit", "nondimensional")
    dep_label = "Departure [MJD2000 UTC days]" if config.get("ephemeris") == "spice" else f"Departure epoch [{time_unit}]"
    with np.load(output / "maps.npz") as data:
        departure = data["departure"]
        tof = data["tof"]
        revolutions = data["revolutions"]
        peak = data["peak"]
        delta_v = (data["delta_v_km_s"] if "delta_v_km_s" in data.files
                   else np.full_like(peak, np.nan))
    aggregate_saved_control_points(output, config, departure, tof, revolutions, peak)
    finite = peak[np.isfinite(peak)]
    if not len(finite):
        print("No accepted solutions; see results.csv and per-cell solver logs.")
        return
    low, high = float(np.min(finite)), float(np.max(finite))
    norm = LogNorm(low, high) if 0 < low < high else Normalize(0, max(high, 1e-12))
    colors = plt.get_cmap("viridis").copy()
    colors.set_bad("#dddddd")

    def draw_peak(ax, values, title):
        mesh = ax.pcolormesh(departure, tof, np.ma.masked_invalid(values),
                             shading="nearest", cmap=colors, norm=norm)
        valid = values[np.isfinite(values)]
        if len(valid) and np.min(valid) < config["u_max"] < np.max(valid):
            contours = ax.contour(departure, tof, np.ma.masked_invalid(values),
                                  levels=[config["u_max"]], colors="crimson", linewidths=1.2)
            ax.clabel(contours, fmt={config["u_max"]: "available u_max"}, fontsize=8)
        ax.set(title=title, xlabel=dep_label,
               ylabel=f"Time of flight [{time_unit}]")
        return mesh

    fig, axes = plt.subplots(2, 3, figsize=(16, 9), constrained_layout=True)
    for index, ax in enumerate(axes.flat):
        mesh = draw_peak(ax, peak[index], f"N = {revolutions[index]}")
    fig.colorbar(mesh, ax=list(axes.flat), label="Lowest peak bound found [nondimensional]")
    scenario = "SPICE Earth to Mars, ecliptic projection" if config.get("ephemeris") == "spice" else "Circular bodies"
    fig.suptitle(f"Minimum-peak shaping by net winding — {scenario}\n"
                 "Gray: no accepted solution; red contour: available u_max; local solutions")
    fig.savefig(output / "porkchop_by_N.png", dpi=180)

    available = np.where(np.isfinite(peak), peak, np.inf)
    best = np.min(available, axis=0)
    best_index = np.argmin(available, axis=0)
    best_n = revolutions[best_index].astype(float)
    best_delta_v = np.take_along_axis(delta_v, best_index[None, :, :], axis=0)[0]
    missing = ~np.isfinite(best)
    best[missing] = np.nan
    best_n[missing] = np.nan
    fig_best, axes = plt.subplots(1, 2, figsize=(13, 5), constrained_layout=True)
    mesh = draw_peak(axes[0], best, "Lowest bound across N = 0,...,5")
    fig_best.colorbar(mesh, ax=axes[0], label="Peak acceleration bound [nondimensional]")
    n_colors = ListedColormap(plt.get_cmap("tab10")(np.arange(6)))
    n_colors.set_bad("#dddddd")
    mesh_n = axes[1].pcolormesh(departure, tof, np.ma.masked_invalid(best_n),
                               shading="nearest", cmap=n_colors,
                               norm=BoundaryNorm(np.arange(-0.5, 6.5), 6))
    axes[1].set(title="N giving the lowest bound found", xlabel=dep_label,
                ylabel=f"Time of flight [{time_unit}]")
    fig_best.colorbar(mesh_n, ax=axes[1], ticks=revolutions, label="Additional complete turns N")
    fig_best.suptitle("Best accepted local solutions — not a global optimality certificate")
    fig_best.savefig(output / "porkchop_best_N.png", dpi=180)

    fig_dv, ax = plt.subplots(figsize=(8, 5.5), constrained_layout=True)
    valid_dv = best_delta_v[np.isfinite(best_delta_v)]
    if len(valid_dv):
        dv_mesh = ax.pcolormesh(departure, tof, np.ma.masked_invalid(best_delta_v),
                                shading="nearest", cmap="plasma")
        fig_dv.colorbar(dv_mesh, ax=ax, label=r"$\Delta V$ [km/s]")
    else:
        ax.text(0.5, 0.5, "No delta-v data in this saved sweep", ha="center", va="center",
                transform=ax.transAxes)
    ax.set(title=r"$\Delta V$ of the trajectory selected by minimum peak bound",
           xlabel=dep_label, ylabel=f"Time of flight [{time_unit}]")
    fig_dv.suptitle(r"Diagnostic $\Delta V=\int\|\mathbf{u}(t)\|dt$; it was not minimized")
    fig_dv.savefig(output / "porkchop_delta_v_at_min_peak.png", dpi=180)

    # Same nondominance rule used by the nominal B-spline shaping
    # postprocessing: sort by Delta-V and retain each strict decrease in u_max.
    valid = np.isfinite(delta_v) & np.isfinite(peak)
    pareto_rows = []
    fig_pareto, ax = plt.subplots(figsize=(7.4, 5.2), constrained_layout=True)
    palette = plt.get_cmap("tab10")
    for ni, n_rev in enumerate(revolutions):
        mask = valid[ni]
        if np.any(mask):
            ax.scatter(delta_v[ni][mask],
                       1000.0 * CANONICAL_ACCEL_TO_M_S2 * peak[ni][mask],
                       s=18, alpha=0.38, color=palette(int(n_rev) % 10),
                       label=f"N={int(n_rev)}")
    indices = np.argwhere(valid)
    if len(indices):
        x = np.asarray([delta_v[tuple(index)] for index in indices])
        y_canonical = np.asarray([peak[tuple(index)] for index in indices])
        order = np.lexsort((y_canonical, x))
        selected = []
        best_u = np.inf
        for position in order:
            value = float(y_canonical[position])
            tolerance = 1.0e-14 * max(1.0, abs(value))
            if not selected or value < best_u - tolerance:
                selected.append(int(position))
                best_u = value
        selected = np.asarray(selected, dtype=int)
        front_order = np.argsort(x[selected])
        selected = selected[front_order]
        front_x = x[selected]
        front_y = 1000.0 * CANONICAL_ACCEL_TO_M_S2 * y_canonical[selected]
        ax.plot(front_x, front_y, color="black", lw=2.0, marker="o",
                markersize=4.5, markerfacecolor="white", markeredgecolor="black",
                label=f"Nondominated front ({len(selected)} points)", zorder=10)
        for position in selected:
            ni, ti, di = indices[position]
            pareto_rows.append({
                "N": int(revolutions[ni]),
                "departure_mjd2000": float(departure[di]),
                "tof_days": float(tof[ti]),
                "delta_v_km_s": float(delta_v[ni, ti, di]),
                "u_required_canonical": float(peak[ni, ti, di]),
                "u_required_mm_s2": float(
                    1000.0 * CANONICAL_ACCEL_TO_M_S2 * peak[ni, ti, di]
                ),
            })
    available_mm_s2 = 1000.0 * CANONICAL_ACCEL_TO_M_S2 * float(config["u_max"])
    ax.axhline(available_mm_s2, color="crimson", ls="--", lw=1.4,
               label=rf"Available $u_{{\max}}={available_mm_s2:.4g}$ mm/s$^2$")
    ax.set(xlabel=r"$\Delta V$ [km/s]",
           ylabel=r"Optimized Bernstein peak bound, $u_{\max}$ [mm/s$^2$]",
           title=r"Earth--Mars planar shaping: $\Delta V$--$u_{\max}$ Pareto diagram")
    ax.grid(True, alpha=0.25)
    ax.legend(fontsize=8, ncol=2)
    fig_pareto.savefig(output / "pareto_delta_v_u_max.png", dpi=180)
    with (output / "pareto_front.csv").open("w", newline="") as stream:
        fields = ["N", "departure_mjd2000", "tof_days", "delta_v_km_s",
                  "u_required_canonical", "u_required_mm_s2"]
        writer = csv.DictWriter(stream, fieldnames=fields)
        writer.writeheader()
        writer.writerows(pareto_rows)
    if show:
        plt.show()
    plt.close(fig)
    plt.close(fig_best)
    plt.close(fig_dv)
    plt.close(fig_pareto)
    print(f"Maps saved in {output.resolve()}")


def run(args):
    omega0 = np.sqrt(args.mu / args.r0**3)
    omegaf = np.sqrt(args.mu / args.rf**3)
    dep_end = args.dep_end
    if dep_end is None:
        if args.ephemeris == "spice":
            # A convenient approximate Earth-Mars synodic window only;
            # actual SPICE states are queried independently at every epoch.
            dep_end = args.dep_start + 780.0
        elif np.isclose(omega0, omegaf, rtol=1e-12, atol=0):
            raise ValueError("Equal orbital rates: specify --dep-end (no finite synodic period)")
        else:
            dep_end = args.dep_start + 2 * np.pi / abs(omegaf - omega0) * DAYS_PER_CANONICAL_TIME
    if dep_end <= args.dep_start:
        raise ValueError("dep-end must exceed dep-start")
    # Exclude the right endpoint: a full synodic period repeats the first column.
    departure = np.linspace(args.dep_start, dep_end, args.dep_count, endpoint=False)
    tof = np.linspace(args.tof_min, args.tof_max, args.tof_count)
    revolutions = np.arange(6)
    peak = np.full((6, len(tof), len(departure)), np.nan)
    sampled_peak = np.full_like(peak, np.nan)
    delta_v_km_s = np.full_like(peak, np.nan)
    control_points = np.full(
        (len(revolutions), len(tof), len(departure), args.n_ctrl, 2), np.nan
    )
    clear_previous_sweep(args.output)
    metadata = {"ephemeris_source": "circular"}
    earth_states, mars_states = {}, {}
    if args.ephemeris == "spice":
        # Fail before running IPOPT if kernels or epoch coverage are missing.
        metadata = spice_metadata(args.spice_meta_kernel)
        kernel = metadata["spice_meta_kernel"]
        for di, epoch in enumerate(departure):
            earth_states[di] = projected_state("EARTH", epoch, kernel)
            for ti, duration in enumerate(tof):
                mars_states[ti, di] = projected_state(args.spice_target_name, epoch + duration, kernel)
        metadata.update(spice_departure_name="EARTH", spice_target_name=args.spice_target_name,
                        projection="Keep ECLIPJ2000 x,y,vx,vy; set z,vz to zero",
                        departure_epoch_convention="MJD2000 UTC, JD2451545.0 origin")
    args.output.mkdir(parents=True, exist_ok=True)
    config = {**vars(args), "output": str(args.output), "dep_end": float(dep_end),
              **metadata,
              "grid_time_unit": "days", "solver_time_unit": "canonical",
              "days_per_canonical_time": DAYS_PER_CANONICAL_TIME,
              "revolutions": revolutions.tolist(), "departure_right_endpoint_excluded": True,
              "meaning_of_N": "additional complete turns beyond wrapped endpoint separation",
              "global_optimality_proven": False}
    (args.output / "config.json").write_text(json.dumps(config, indent=2) + "\n")
    total = peak.size
    fields = ["N", "departure_days", "departure_mjd2000", "tof_days", "departure_canonical", "tof_canonical",
              "theta_final", "status", "peak_bound",
              "sampled_peak", "delta_v_reference_km_s", "delta_v_reference_error_km_s",
              "delta_v_reference_converged", "gap_to_u_max",
              "available_limit_checks_passed", "cell_path", "error"]
    tasks = []
    for ni, n_rev in enumerate(revolutions):
        for ti, duration in enumerate(tof):
            for di, epoch in enumerate(departure):
                duration_canonical = float(duration / DAYS_PER_CANONICAL_TIME)
                epoch_canonical = float(epoch / DAYS_PER_CANONICAL_TIME)
                separation = (args.target_phase + omegaf * (epoch_canonical + duration_canonical)
                              - omega0 * epoch_canonical)
                velocities = None
                r0, rf = args.r0, args.rf
                ephemeris_payload = None
                if args.ephemeris == "spice":
                    initial, initial_record = earth_states[di]
                    final, final_record = mars_states[ti, di]
                    r0, rf = float(initial[0]), float(final[0])
                    separation = final[1] - initial[1]
                    velocities = np.vstack((initial[2:], final[2:]))
                angle = float(np.remainder(separation, 2 * np.pi) + 2 * np.pi * n_rev)
                cell = args.output / "cells" / f"N{n_rev}_tof{ti:03d}_dep{di:03d}"
                if args.ephemeris == "spice":
                    ephemeris_payload = {
                        **metadata, "departure": initial_record, "arrival": final_record,
                        "frame_rotation_rad": float(initial[1]),
                        "theta_final_unwrapped_rad": angle, "N": int(n_rev),
                    }
                options = argparse.Namespace(
                    mode="min-peak", degree=args.degree, n_ctrl=args.n_ctrl,
                    mu=args.mu, r0=r0, rf=rf,
                    tof=duration_canonical, theta_final=angle, u_max=args.u_max,
                    rho_min=args.rho_min, subdivide=args.subdivide, quadrature=args.quadrature,
                    samples=args.samples, max_iter=args.max_iter, quiet=True,
                    no_plots=True, show_plots=False, output=cell,
                )
                row = dict(N=int(n_rev), departure_days=float(epoch), tof_days=float(duration),
                           departure_mjd2000=float(epoch) if args.ephemeris == "spice" else "",
                           departure_canonical=epoch_canonical, tof_canonical=duration_canonical,
                           theta_final=angle, status="failed", peak_bound="", sampled_peak="",
                           delta_v_reference_km_s="", delta_v_reference_error_km_s="",
                           delta_v_reference_converged="",
                           gap_to_u_max="", available_limit_checks_passed="",
                           cell_path=str(cell), error="")
                tasks.append({
                    "indices": (ni, ti, di),
                    "cell": str(cell),
                    "options": options,
                    "endpoint_velocities": velocities,
                    "ephemeris_payload": ephemeris_payload,
                    "row": row,
                })

    print(f"Running {total} cells with {args.workers} worker process(es).", flush=True)
    with (args.output / "results.csv").open("w", newline="") as stream:
        writer = csv.DictWriter(stream, fieldnames=fields)
        writer.writeheader()
        done = 0

        def store_result(completed):
            nonlocal done
            (ni, ti, di), row, value, sampled_value, delta_v_value, controls = completed
            if row["status"] == "accepted":
                peak[ni, ti, di] = value
                sampled_peak[ni, ti, di] = sampled_value
                delta_v_km_s[ni, ti, di] = delta_v_value
                control_points[ni, ti, di] = controls
            writer.writerow(row)
            stream.flush()
            # Only the parent writes shared aggregate files.
            np.savez_compressed(args.output / "maps.npz", departure=departure, tof=tof,
                                revolutions=revolutions, peak=peak, sampled_peak=sampled_peak,
                                delta_v_km_s=delta_v_km_s)
            done += 1
            # Full control-point checkpoints are less frequent because the
            # individual solution.json files already provide per-cell recovery.
            if done == total or done % 50 == 0:
                np.savez_compressed(
                    args.output / "control_points.npz",
                    control_points=control_points,
                    departure_mjd2000=departure,
                    tof_days=tof,
                    N=revolutions,
                    accepted=np.isfinite(peak),
                    degree=np.asarray(args.degree),
                    n_ctrl=np.asarray(args.n_ctrl),
                    knots=make_clamped_knots(args.n_ctrl, args.degree),
                    coordinates=np.asarray(["rho", "theta"]),
                    array_layout=np.asarray(
                        "control_points[N_index,tof_index,departure_index,control_index,coordinate]"
                    ),
                )
            detail = (f"u_required={value:.6g}, dV={delta_v_value:.6g} km/s"
                      if row["status"] == "accepted" else "failed (see log)")
            print(f"[{done}/{total}] N={row['N']}, dep={row['departure_days']:.4g} d, "
                  f"TOF={row['tof_days']:.4g} d: {detail}", flush=True)

        if args.workers == 1:
            for task in tasks:
                store_result(solve_cell(task))
        else:
            with ProcessPoolExecutor(max_workers=args.workers) as executor:
                futures = [executor.submit(solve_cell, task) for task in tasks]
                for future in as_completed(futures):
                    store_result(future.result())
    plot_maps(args.output, args.show_plots)


def main():
    parser = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    parser.add_argument("--ephemeris", choices=("spice", "circular"), default="spice")
    parser.add_argument("--spice-meta-kernel", default="kernels/fasttransfer_planets.tm",
                        help="Same SPICE meta-kernel as nominal shaping; run from repository root")
    parser.add_argument("--spice-target-name", choices=("MARS BARYCENTER", "MARS"), default="MARS BARYCENTER",
                        help="de440s provides Mars barycenter; MARS needs an additional satellite SPK")
    parser.add_argument("--dep-start", type=departure_epoch, default="2028-01-01",
                        help="MJD2000 UTC days or YYYY-MM-DD; circular mode accepts days from its epoch")
    parser.add_argument("--dep-end", type=departure_epoch, default=None,
                        help="Same convention as dep-start; default: +780 days for SPICE, one synodic period for circular")
    parser.add_argument("--dep-count", type=int, default=7)
    parser.add_argument("--tof-min", type=float, default=500.0, help="Minimum time of flight [days]")
    parser.add_argument("--tof-max", type=float, default=1500.0, help="Maximum time of flight [days]")
    parser.add_argument("--tof-count", type=int, default=9)
    parser.add_argument("--target-phase", type=float, default=0.0, help="Circular mode only: target angle at epoch zero [rad]")
    parser.add_argument("--mu", type=float, default=1.0)
    parser.add_argument("--r0", type=float, default=1.0, help="Circular mode only: departure radius [AU]")
    parser.add_argument("--rf", type=float, default=1.5, help="Circular mode only: target radius [AU]")
    parser.add_argument("--u-max", type=float, default=0.2, help="Comparison contour and solver scale; not a hard cap")
    parser.add_argument("--rho-min", type=float, default=0.2)
    parser.add_argument("--degree", type=int, choices=(3, 5), default=3,
                        help="B-spline degree: cubic (3) or quintic (5)")
    parser.add_argument("--n-ctrl", type=int, default=8,
                        help="Total clamped B-spline control points per coordinate")
    parser.add_argument("--subdivide", type=int, default=1)
    parser.add_argument("--quadrature", type=int, default=12)
    parser.add_argument("--samples", type=int, default=2001)
    parser.add_argument("--max-iter", type=int, default=2000)
    parser.add_argument("--workers", type=int, default=1,
                        help="Independent IPOPT worker processes (default: 1)")
    parser.add_argument("--output", type=Path, default=Path("output/porkchop_planar_spice_earth_mars_nctrl8_deg3_tof500_1500d"))
    parser.add_argument("--show-plots", action="store_true")
    parser.add_argument("--plot-only", action="store_true", help="Plot saved maps without running IPOPT")
    args = parser.parse_args()
    if args.plot_only:
        plot_maps(args.output, args.show_plots)
        return
    if args.ephemeris == "spice" and args.mu != 1.0:
        parser.error("SPICE mode uses the nominal solver's solar canonical mu=1")
    positive = (args.mu, args.r0, args.rf, args.u_max, args.rho_min, args.tof_min, args.tof_max)
    if any(not np.isfinite(v) or v <= 0 for v in positive):
        parser.error("mu, radii, u-max and flight times must be finite and positive")
    if not np.isfinite(args.dep_start) or not np.isfinite(args.target_phase):
        parser.error("dep-start and target-phase must be finite")
    if args.dep_end is not None and (not np.isfinite(args.dep_end) or args.dep_end <= args.dep_start):
        parser.error("dep-end must be finite and exceed dep-start")
    if args.tof_max <= args.tof_min or min(args.dep_count, args.tof_count) < 2:
        parser.error("tof-max must exceed tof-min; both grid counts must be >= 2")
    if args.ephemeris == "circular" and args.rho_min > min(args.r0, args.rf):
        parser.error("rho-min cannot exceed either endpoint radius")
    if (args.n_ctrl < args.degree + 2 or args.subdivide < 0 or args.quadrature < 1
            or args.samples < 2 or args.max_iter < 1 or args.workers < 1):
        parser.error("Require at least two spans, subdivide>=0, quadrature>=1, "
                     "samples>=2, max-iter>=1, workers>=1")
    run(args)


if __name__ == "__main__":
    main()
