"""Planar Earth-to-Mars SPICE porkchop of minimum peak bounds for N=0,...,5.

Run from the repository root:
    python -m experiments.porkchop_planar_min_peak --dep-count 5 --tof-count 7 --workers 4

N denotes additional complete prograde turns in the unwrapped endpoint angle,
using the same wrap-to-[0,2pi) plus 2*pi*N convention as the 3D shaping sweep.
This fixes net winding; it does not impose monotone angular motion.
CLI times, CSV departure/TOF columns, and map axes use days. Internally the
solver uses the repository's canonical units: 1 AU and UT=1/(2*pi) years.
Radii are in AU; mu and accelerations remain in canonical units. By default,
use the nominal shaping workflow's SPICE reader in ECLIPJ2000, SUN observer,
NONE aberration. Keep x,y,vx,vy and discard z,vz. The de440s kernel supplies
MARS BARYCENTER, used explicitly by default (not the Mars center, NAIF 499).
This is a planar projection experiment, not a full 3D planetary rendezvous.
Spacecraft dynamics remain planar two-body gravity plus thrust; there is no
SPICE force model. Each solve is rotated to the departure body's angle.
Use --ephemeris circular to recover the idealized circular-orbit experiment.

Values are locally optimized sufficient Bernstein bounds, NOT proven global
minima. Failed solves are missing data, not evidence of infeasibility. Each
cell uses one Hermite seed; no multistart search is performed.
"""

